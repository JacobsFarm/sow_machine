FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
STL_DIR = os.path.join(FOLDER, "stl")
DOC_NAME = "Overseeder_Mini_TT"
SAVE_BASE = os.path.join(FOLDER, DOC_NAME)
ROOT = "Overseeder_mini_tt"
METER = "Meter"

COLOR = dict(B.COLOR, motor=(0.98, 0.82, 0.10), shaft=(0.93, 0.93, 0.90))

# name: (function, label, color, density or None for bought, print rotation (axis, degrees))
PARTS = {
    "body": (G.body, "hopper_body_PETG", "body", P.petg, ((0, 1, 0), -90.0)),
    "motor_plate": (G.motor_plate, "motor_plate_TT_PETG", "plate", P.petg, ((0, 1, 0), 90.0)),
    "roller": (lambda: G.roller(T.DEFAULT), "cam_roller_%s_TT_PETG" % T.DEFAULT, "roller", P.petg, ((0, 1, 0), 90.0)),
    "rim": (G.rim, "cutoff_rim_PETG", "rim", P.petg, ((0, 0, 1), 0.0)),
    "lid": (G.lid, "lid_PETG", "lid", P.petg, ((1, 0, 0), 180.0)),
    "tray": (G.tray, "catch_tray_PETG", "tray", P.petg, ((0, 0, 1), 0.0)),
    "tt_motor": (G.tt_motor, "TT_gear_motor_1to48", "motor", None, None),
    "tt_shaft": (G.tt_shaft, "TT_shaft_5.4_DD_3.7", "shaft", None, None),
    "bolt": (G.bolt_set, "bolt_M8x100_washers_nut", "shaft", None, None),
    "motor_bolts": (G.motor_bolts, "motor_bolts_M3x25_nuts", "shaft", None, None),
}
TOUCHING = {("tt_motor", "tt_shaft")}


def add_shape(doc, parent, name, shape):
    _, label, color, _, _ = PARTS[name]
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
    return obj


def build(save=True, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Overseeder mini TT motor"
    doc.Comment = ("Generated by tt_motor/build_ovt.py from ovt_params.py and ../ovm_params.py. Local frame: "
                   "x = along the roller, y = forward, z = up, origin = roller axis.")
    root = B.new_part(doc, None, ROOT, "overseeder_mini_tt_motor")
    hop = B.new_part(doc, root, "Hopper", "hopper")
    for n in ("body", "lid", "rim"):
        add_shape(doc, hop, n, PARTS[n][0]())
    drv = B.new_part(doc, root, "Drive", "drive_tt_motor")
    for n in ("motor_plate", "tt_motor", "bolt", "motor_bolts"):
        add_shape(doc, drv, n, PARTS[n][0]())
    spin = B.new_part(doc, root, METER, "meter_roller_rotates")
    add_shape(doc, spin, "roller", PARTS["roller"][0]())
    add_shape(doc, spin, "tt_shaft", G.tt_shaft())
    cal = B.new_part(doc, root, "Calibration", "calibration")
    add_shape(doc, cal, "tray", G.tray())
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        import Import
        Import.export(objects(doc), SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("build_ovt.build() first")


def objects(doc):
    return [o for o in doc.getObject(ROOT).OutListRecursive if o.TypeId == "Part::Feature"]


def set_roller(angle_deg, doc=None):
    doc = active_doc(doc)
    doc.getObject(METER).Placement = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -angle_deg))
    doc.recompute()


def check_interference(doc=None, tol=0.5, angles=(0.0, 6.4, 12.9, 19.3, 45.0, 90.0)):
    """Volume overlap (mm3) between all parts at a few roller angles (the double-D shaft turns with the roller)."""
    doc = active_doc(doc)
    hits = []
    for a in angles:
        set_roller(a, doc)
        objs = [(o, B.global_shape(o)) for o in objects(doc)]
        for i in range(len(objs)):
            for j in range(i + 1, len(objs)):
                (oa, sa), (ob, sb) = objs[i], objs[j]
                if not sa.BoundBox.intersect(sb.BoundBox):
                    continue
                vol = sa.common(sb).Volume
                if vol > tol and tuple(sorted((oa.Name, ob.Name))) not in TOUCHING:
                    hits.append((a, oa.Label, ob.Label, round(vol, 1)))
    set_roller(0.0, doc)
    return {"hits": hits}


def check_variants(doc=None):
    doc = active_doc(doc)
    out = {}
    o = doc.getObject("roller")
    for k in T.VARIANTS:
        o.Shape = G.roller(k)
        doc.recompute()
        out[k] = check_interference(doc, angles=(0.0, 6.4, 12.9, 19.3))
    o.Shape = G.roller(T.DEFAULT)
    doc.recompute()
    return out


def check_engagement():
    """Length of TT shaft inside the roller socket and the socket fit (mm)."""
    shaft_tip = G.X_MOT - T.tt_shaft_out[0]
    return {"shaft_in_roller": round(G.X1 - shaft_tip, 2), "socket_depth": T.socket_depth,
            "journal_in_end_wall": round(P.journal[1] - P.roller_end_gap, 2),
            "motor_end_in_bearing": round(G.X1 - G.X_IN, 2),
            "motor_end_bearing_cylinder": round(G.X1 - G.X_IN - T.end_chamfer, 2),
            "roller_end_to_pocket_bottom": round(G.X_POCKET - G.X1, 2),
            "radial_gap_in_pocket": round((T.pocket[0] - T.roller_end_d) / 2.0, 2),
            "bolt_head_to_pocket": round(math.hypot(T.tt_holes[1] / 2.0, T.tt_holes[0]) - T.motor_bolt[1] / 2.0
                                         - T.pocket[0] / 2.0, 2),
            "bolt_head_to_roller_end": round(G.X_IN - P.roller_x[1], 2),
            "socket": (T.tt_shaft[0] + 2 * T.socket_clear, T.tt_shaft[1] + 2 * T.socket_clear),
            "bolt": G.bolt_check()}


def part_shape(name):
    if name.startswith("roller_"):
        return G.roller(name.split("_", 1)[1])
    return PARTS[name][0]()


def print_shape(name):
    s = part_shape(name)
    axis, deg = PARTS["roller" if name.startswith("roller_") else name][4]
    if name.startswith("roller_") and P.ROLLERS[name.split("_", 1)[1]].get("chamfer") == "-x":
        deg = -deg                                  # roller I stands on its journal end
    s.rotate(V(0, 0, 0), V(*axis), deg)
    bb = s.optimalBoundingBox()
    s.translate(V(-(bb.XMin + bb.XMax) / 2.0, -(bb.YMin + bb.YMax) / 2.0, -bb.ZMin))
    return s


def printed():
    return [n for n, v in PARTS.items() if v[3] is not None]


def printed_all():
    return [n for n in printed() if n != "roller"] + ["roller_%s" % k for k in T.VARIANTS]


def print_sizes():
    out = {}
    for n in printed_all():
        bb = print_shape(n).optimalBoundingBox()
        out[n] = (round(bb.XLength), round(bb.YLength), round(bb.ZLength))
    return out


def check_fit():
    bx, by, bz = P.bed
    out = {}
    for n, (x, y, z) in print_sizes().items():
        xy = sorted((x, y))
        if not (xy[0] <= min(bx, by) and xy[1] <= max(bx, by) and z <= bz):
            out[n] = (x, y, z)
    return out


def mass_properties():
    parts, total = {}, 0.0
    for n in printed_all():
        g = part_shape(n).Volume * P.petg * P.infill_eff
        parts[n] = round(g, 1)
    base = sum(v for k, v in parts.items() if not k.startswith("roller_")) + parts["roller_%s" % T.DEFAULT]
    return {"parts_g": parts, "base_set_g": round(base), "filament_eur": round(base / 1000.0 * P.filament_eur_kg, 2)}


def export_stl(folder=STL_DIR, deflection=0.02):
    import MeshPart
    os.makedirs(folder, exist_ok=True)
    out = []
    for n in printed_all():
        mesh = MeshPart.meshFromShape(Shape=print_shape(n), LinearDeflection=deflection, AngularDeflection=0.1,
                                      Relative=False)
        path = os.path.join(folder, "ovt_%s.stl" % n)
        mesh.write(path)
        out.append(path)
    return out


