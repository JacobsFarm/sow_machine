def save_view(name, direction, **kw):
    old = B.PREVIEW_DIR
    B.PREVIEW_DIR = PREVIEW_DIR
    try:
        return B.save_view(name, direction, **kw)
    finally:
        B.PREVIEW_DIR = old


def explode(doc, offsets):
    for n, (dx, dy, dz) in offsets.items():
        doc.getObject(n).Placement = App.Placement(V(dx, dy, dz), App.Rotation())


EXPLODE = {"lid": (0, 0, 70), "motor_plate": (60, 0, 0), "tt_motor": (110, 0, 0), "rim": (0, 70, 0),
           "tray": (0, 0, -50), "bolt": (-130, 0, 0)}


def render_all():
    out = []
    doc = build(save=False, step=False)
    out.append(save_view("1_iso.png", (-1.0, -1.1, -0.8), height=330))
    out.append(save_view("2_motor_side.png", (-1.0, 0.0, 0.0), target=(0, 0, 30), height=230))
    B.set_visible(doc, ("lid", "body", "rim", "tray"), False)
    out.append(save_view("3_motor_mount_detail.png", (-0.6, 1.0, -0.35), target=(G.X_IN, 0, 10), height=120))
    B.set_visible(doc, ("lid", "body", "rim", "tray"), True)
    explode(doc, EXPLODE)
    doc.getObject("tt_shaft").Placement = App.Placement(V(110, 0, 0), App.Rotation())
    doc.getObject(METER).Placement = App.Placement(V(25, 0, 0), App.Rotation())
    out.append(save_view("4_exploded.png", (-0.9, 1.0, -0.6), target=(20, 0, 20), height=420))
    App.closeDocument(doc.Name)
    out.append(render_plate())
    out.append(render_rollers())
    build()
    return out


def render_plate():
    """Motor plate alone, inner face (with the roller pocket) towards the viewer."""
    name = "Overseeder_Mini_TT_Plate"
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    o = doc.addObject("Part::Feature", "plate")
    o.Shape = G.motor_plate()
    o.ViewObject.ShapeColor = COLOR["plate"]
    doc.recompute()
    path = save_view("5_motor_plate_inner_face.png", (1.0, 0.25, -0.2), target=(G.X_IN, 0, 30), height=160)
    App.closeDocument(doc.Name)
    return path


def render_rollers(keys=("F", "I")):
    """Rollers side by side as they stand on the bed, with a letter under each (F on its motor end, I on its journal end (tree
    support from the slicer under it); the cam chamfers face down on both)."""
    name = "Overseeder_Mini_TT_Rollers"
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    step = P.roller_d + 25.0
    for i, k in enumerate(keys):
        s = print_shape("roller_%s" % k)
        s.translate(V(i * step, 0, 0))
        o = doc.addObject("Part::Feature", "roller_" + k)
        o.Shape = s
        o.ViewObject.ShapeColor = COLOR["roller"]
        try:
            import Draft
            t = Draft.make_text([k], App.Placement(V(i * step - 4, -P.roller_d, -9), App.Rotation(V(1, 0, 0), 90)))
            t.ViewObject.FontSize = 12
            t.ViewObject.TextColor = (0.0, 0.0, 0.0)
        except Exception:
            pass
    doc.recompute()
    path = save_view("6_rollers_F_and_I_as_printed.png", (0.0, 1.0, -0.25), target=((len(keys) - 1) * step / 2.0, 0, 36),
                     height=120, size_px=(1400, 1100))
    App.closeDocument(doc.Name)
    return path