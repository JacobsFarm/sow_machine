"""Model of the TT gear motor version of the mini drop seeder: hopper body, cut-off rim, lid and tray from the base
design, motor plate with roller pocket, cam roller with double-D socket, TT gear motor.

Use in FreeCAD 1.1 (via run_in_freecad.py in this folder):
    import build_ovt
    build_ovt.build()                   # saves FCStd and STEP in this folder
    build_ovt.check_interference()      # must be empty
    build_ovt.check_variants()          # the same with each roller in ovt_params.VARIANTS
    build_ovt.check_fit()               # printed parts that do not fit the A1 bed: must be empty
    build_ovt.mass_properties()         # filament per part
    build_ovt.export_stl()              # stl/ovt_<part>.stl and stl/ovt_roller_<k>.stl, in the print orientation
    build_ovt.render_all()              # previews/
"""
