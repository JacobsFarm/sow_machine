def new_part(doc, parent, name, label, placement=None):
    part = doc.addObject("App::Part", name)
    part.Label = label
    if placement is not None:
        part.Placement = placement
    if parent is not None:
        parent.addObject(part)
    return part


def add_shape(doc, parent, name, shape, visible=True):
    _, label, color, _, _ = PARTS[name]
    obj = doc.addObject("Part::Feature", name)
    obj.Label = label
    obj.Shape = shape
    parent.addObject(obj)
    if obj.ViewObject is not None:
        obj.ViewObject.ShapeColor = COLOR[color]
        obj.ViewObject.Visibility = visible
    return obj


def build(save=True, step=True):
    if DOC_NAME in App.listDocuments():
        App.closeDocument(DOC_NAME)
    doc = App.newDocument(DOC_NAME)
    doc.Label = "Overseeder mini print"
    doc.Comment = ("Generated by build_ovm.py from ovm_params.py. Local frame: x = along the roller, y = forward, "
                   "z = up, origin = roller axis.")
    root = new_part(doc, None, ROOT, "overseeder_mini_drop_seeder_3d_print")
    hop = new_part(doc, root, "Hopper", "hopper")
    for n in ("body", "lid", "rim"):
        add_shape(doc, hop, n, PARTS[n][0]())
    drv = new_part(doc, root, "Drive", "drive_nema17")
    for n in ("motor_plate", "stepper"):
        add_shape(doc, drv, n, PARTS[n][0]())
    spin = new_part(doc, root, METER, "meter_roller_rotates")
    add_shape(doc, spin, "roller", G.roller())
    add_shape(doc, spin, "stepper_shaft", G.stepper_shaft())
    calib = new_part(doc, root, "Calibration", "calibration")
    add_shape(doc, calib, "tray", G.tray())
    doc.recompute()
    if save:
        doc.saveAs(SAVE_BASE + ".FCStd")
    if step:
        export_step(doc, SAVE_BASE + ".step")
    return doc


def active_doc(doc=None):
    if doc is not None:
        return doc
    if DOC_NAME in App.listDocuments():
        return App.getDocument(DOC_NAME)
    raise RuntimeError("build_ovm.build() first")


def objects(doc):
    return [o for o in doc.getObject(ROOT).OutListRecursive if o.TypeId == "Part::Feature"]


def global_shape(obj):
    s = obj.Shape.copy()
    s.Placement = obj.getGlobalPlacement()
    return s


def set_roller(angle_deg, doc=None):
    """Turn the roller (+ = the top moves forward, +y; the front side moves down past the lip)."""
    doc = active_doc(doc)
    doc.getObject(METER).Placement = App.Placement(V(0, 0, 0), App.Rotation(V(1, 0, 0), -angle_deg))
    doc.recompute()


def export_step(doc, path):
    import Import
    Import.export(objects(doc), path)


