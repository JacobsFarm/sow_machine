"""Model of the mini drop seeder for 3D printing: hopper, fluted or cam roller, cut-off rim, motor plate, lid,
catch tray, NEMA 17 stepper.

Use in FreeCAD (folder on sys.path, or via run_in_freecad.py):
    import build_ovm
    build_ovm.build()                   # saves FCStd and STEP
    build_ovm.check_interference()      # must be empty (the rim does not touch the roller)
    build_ovm.check_variants()          # check_interference() with each roller variant A..H (P.ROLLERS)
    build_ovm.check_fit()               # every printed part on the bed in its print orientation: must be empty
    build_ovm.mass_properties()         # filament per part, total, cost
    build_ovm.roller_variants()         # filament and modelled flute volume per roller variant vs ovm_calc
    build_ovm.export_stl()              # stl/<part>.stl and stl/ovm_roller_<B..H>.stl, in the print orientation
    build_ovm.set_roller(30)            # turn the roller (degrees, + = the top moves forward)
    build_ovm.render_all()

Stands on its own (no robot model): local frame of ovm_params, origin = roller axis.
"""
import os

import FreeCAD as App
import Part
from FreeCAD import Vector as V

import ovm_params as P
import ovm_parts as G

FOLDER = os.path.dirname(os.path.abspath(__file__))
PREVIEW_DIR = os.path.join(FOLDER, "previews")
STL_DIR = os.path.join(FOLDER, "stl")
DOC_NAME = "Overseeder_Mini_Print"
SAVE_BASE = os.path.join(FOLDER, "Overseeder_Mini_Print")
ROOT = "Overseeder_mini"
METER = "Meter"

COLOR = {
    "body": (0.20, 0.62, 0.32),
    "plate": (0.55, 0.57, 0.60),
    "roller": (0.95, 0.75, 0.10),
    "rim": (0.08, 0.08, 0.08),
    "lid": (0.30, 0.75, 0.42),
    "tray": (0.35, 0.55, 0.85),
    "motor": (0.12, 0.12, 0.13),
    "shaft": (0.75, 0.75, 0.78),
}

# name: (function, label, color, material density or None for bought, print rotation (axis, degrees))
PARTS = {
    "body": (G.body, "hopper_body_PETG", "body", P.petg, ((0, 1, 0), -90.0)),
    "motor_plate": (G.motor_plate, "motor_plate_PETG", "plate", P.petg, ((0, 1, 0), 90.0)),
    "roller": (G.roller, "fluted_roller_D40_12_flutes_PETG", "roller", P.petg, ((0, 1, 0), 90.0)),
    "rim": (G.rim, "cutoff_rim_PETG", "rim", P.petg, ((0, 0, 1), 0.0)),
    "lid": (G.lid, "lid_PETG", "lid", P.petg, ((1, 0, 0), 180.0)),
    "tray": (G.tray, "catch_tray_PETG", "tray", P.petg, ((0, 0, 1), 0.0)),
    "stepper": (G.stepper, "stepper_NEMA17_42x40", "motor", None, None),
    "stepper_shaft": (G.stepper_shaft, "stepper_shaft_D5", "shaft", None, None),
}
VARIANTS = [k for k in P.ROLLERS if k != P.ROLLER_DEFAULT]     # extra rollers: stl/ovm_roller_<k>.stl
TOUCHING = {("stepper", "stepper_shaft")}   # one motor, shaft drawn separately so it turns with the roller


