def save_view(name, direction, target=(0, 0, 40), height=None, up=(0.0, 0.0, 1.0), size_px=(1600, 1100)):
    import FreeCADGui as Gui
    from pivy import coin
    Gui.updateGui()
    view = Gui.ActiveDocument.ActiveView
    view.setCameraType("Orthographic")
    d = V(*direction)
    d.normalize()
    cam = view.getCameraNode()
    tgt = V(*target)
    eye = tgt - d * 2000.0
    cam.position.setValue(coin.SbVec3f(eye.x, eye.y, eye.z))
    cam.pointAt(coin.SbVec3f(tgt.x, tgt.y, tgt.z), coin.SbVec3f(*up))
    cam.nearDistance.setValue(1.0)
    cam.farDistance.setValue(5000.0)
    if height is None:
        view.fitAll()
    else:
        cam.height.setValue(height)
    Gui.updateGui()
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    path = os.path.join(PREVIEW_DIR, name)
    view.saveImage(path, size_px[0], size_px[1], "White")
    return path


def set_visible(doc, names, visible):
    for n in names:
        o = doc.getObject(n)
        if o is not None:
            o.ViewObject.Visibility = visible


def explode(doc, offsets):
    for n, (dx, dy, dz) in offsets.items():
        o = doc.getObject(n)
        o.Placement = App.Placement(V(dx, dy, dz), App.Rotation())


EXPLODE = {"lid": (0, 0, 70), "motor_plate": (90, 0, 0), "stepper": (150, 0, 0), "rim": (0, 70, 0),
           "tray": (0, 0, -50)}


def render_all():
    import FreeCADGui as Gui
    out = []
    doc = build(save=False, step=False)
    out.append(save_view("1_iso.png", (-1.0, -1.1, -0.8), height=330))
    set_visible(doc, ("motor_plate", "stepper", "lid"), False)
    set_roller(7.5, doc)
    out.append(save_view("2_section_from_motor_side.png", (-1.0, 0.0, 0.0), target=(0, 0, 20), height=230))
    set_roller(0.0, doc)
    set_visible(doc, ("motor_plate", "stepper", "lid"), True)
    explode(doc, EXPLODE)
    set_visible(doc, ("rim",), True)
    doc.getObject(METER).Placement = App.Placement(V(45, 0, 0), App.Rotation())
    out.append(save_view("3_exploded.png", (-0.9, 1.0, -0.6), target=(60, 0, 30), height=420))
    explode(doc, {n: (0, 0, 0) for n in EXPLODE})
    doc.getObject(METER).Placement = App.Placement()
    set_visible(doc, ("tray",), False)
    out.append(save_view("4_from_below.png", (-0.7, -0.9, 1.0), height=330))
    App.closeDocument(doc.Name)
    out.append(render_print_layout())
    out.append(render_roller_variants())
    build()
    return out


def render_roller_variants():
    """All rollers standing side by side as printed (motor end down), A to H from left to right, with a letter
    in front of each."""
    import FreeCADGui as Gui
    name = "Overseeder_Mini_Rollers"
    if name in App.listDocuments():
        App.closeDocument(name)
    doc = App.newDocument(name)
    step = P.roller_d + 25.0
    for i, k in enumerate(P.ROLLERS):
        s = G.roller(k)
        s.rotate(V(0, 0, 0), V(0, 1, 0), 90.0)
        bb = s.optimalBoundingBox()
        s.translate(V(i * step - (bb.XMin + bb.XMax) / 2.0, -(bb.YMin + bb.YMax) / 2.0, -bb.ZMin))
        o = doc.addObject("Part::Feature", "roller_" + k)
        o.Shape = s
        o.ViewObject.ShapeColor = COLOR["roller"]
        try:
            import Draft
            t = Draft.make_text([k], App.Placement(V(i * step - 4, -P.roller_d, -18), App.Rotation(V(1, 0, 0), 90)))
            t.ViewObject.FontSize = 14
            t.ViewObject.TextColor = (0.0, 0.0, 0.0)
        except Exception:
            pass
    doc.recompute()
    Gui.updateGui()
    mid = (len(P.ROLLERS) - 1) / 2.0 * step
    Gui.Selection.clearSelection()
    path = save_view("6_roller_variants.png", (0.0, 1.0, -0.3), target=(mid, 0, 70),
                     height=len(P.ROLLERS) * step / 1.6 + 20, size_px=(1600, 1000))
    App.closeDocument(doc.Name)
    return path


def render_print_layout():
    """All printed parts in their print orientation side by side on z = 0."""
    import FreeCADGui as Gui
    if "Overseeder_Mini_Layout" in App.listDocuments():
        App.closeDocument("Overseeder_Mini_Layout")
    doc = App.newDocument("Overseeder_Mini_Layout")
    x = 0.0
    for n in printed():
        s = print_shape(n)
        bb = s.optimalBoundingBox()
        s.translate(V(x - bb.XMin, 0, 0))
        o = doc.addObject("Part::Feature", n)
        o.Shape = s
        o.ViewObject.ShapeColor = COLOR[PARTS[n][2]]
        x += bb.XLength + 25.0
    bed = doc.addObject("Part::Feature", "bed")
    bed.Shape = Part.makeBox(x, 260, 1, V(-15, -130, -1))
    bed.ViewObject.ShapeColor = (0.85, 0.85, 0.85)
    doc.recompute()
    Gui.updateGui()
    path = save_view("5_print_layout.png", (-0.5, 1.0, -0.8), target=(x / 2.0, 0, 40))
    App.closeDocument(doc.Name)
    return path
