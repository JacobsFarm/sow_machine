def check_interference(doc=None, tol=0.5, angles=(0.0, 7.5, 15.0)):
    """Volume overlap (mm3) between all parts, at a few roller angles (the flutes or cams pass the rim)."""
    doc = active_doc(doc)
    hits = []
    for a in angles:
        set_roller(a, doc)
        objs = [(o, global_shape(o)) for o in objects(doc)]
        for i in range(len(objs)):
            for j in range(i + 1, len(objs)):
                (oa, sa), (ob, sb) = objs[i], objs[j]
                if not sa.BoundBox.intersect(sb.BoundBox):
                    continue
                vol = sa.common(sb).Volume
                if vol <= tol:
                    continue
                key = tuple(sorted((oa.Name, ob.Name)))
                if key in TOUCHING:
                    continue
                hits.append((a, oa.Label, ob.Label, round(vol, 1)))
    set_roller(0.0, doc)
    return {"hits": hits}


def set_variant(variant, doc=None):
    """Put roller variant k (P.ROLLERS) in the model, for the checks; build() always puts in the default."""
    doc = active_doc(doc)
    o = doc.getObject("roller")
    o.Shape = G.roller(variant)
    o.Label = "roller_%s_%s_PETG" % (variant, P.ROLLERS[variant]["label"].replace(" ", "_").replace(",", ""))
    doc.recompute()


def check_variants(doc=None):
    """check_interference() with every roller variant in turn, at angles over one flute / stud pitch."""
    doc = active_doc(doc)
    out = {}
    for k in P.ROLLERS:
        set_variant(k, doc)
        out[k] = check_interference(doc, angles=(0.0, 6.4, 12.9, 19.3))
    set_variant(P.ROLLER_DEFAULT, doc)
    doc.getObject("roller").Label = PARTS["roller"][1]
    return out


def part_shape(name):
    """Shape of a part; 'roller_<k>' is roller variant k (P.ROLLERS), 'roller' the default."""
    if name.startswith("roller_"):
        return G.roller(name.split("_", 1)[1])
    return PARTS[name][0]()


def part_spec(name):
    return PARTS["roller" if name.startswith("roller_") else name]


def print_shape(name):
    """The part rotated into its print orientation, standing on z = 0 and centred on the bed."""
    s = part_shape(name)
    axis, deg = part_spec(name)[4]
    s.rotate(V(0, 0, 0), V(*axis), deg)
    bb = s.optimalBoundingBox()   # exact: BoundBox of the swept flutes is loose
    s.translate(V(-(bb.XMin + bb.XMax) / 2.0, -(bb.YMin + bb.YMax) / 2.0, -bb.ZMin))
    return s


def printed():
    return [n for n, v in PARTS.items() if v[3] is not None]


def printed_all():
    """Printed parts plus the extra roller variants."""
    return printed() + ["roller_%s" % k for k in VARIANTS]


def check_fit():
    """Printed parts (and roller variants) that do not fit the bed (P.bed) in the print orientation: must be
    empty."""
    bx, by, bz = P.bed
    out = {}
    for n in printed_all():
        bb = print_shape(n).optimalBoundingBox()
        xy = sorted((bb.XLength, bb.YLength))
        if not (xy[0] <= min(bx, by) and xy[1] <= max(bx, by) and bb.ZLength <= bz):
            out[n] = (round(bb.XLength), round(bb.YLength), round(bb.ZLength))
    return out


def print_sizes():
    out = {}
    for n in printed_all():
        bb = print_shape(n).optimalBoundingBox()
        out[n] = (round(bb.XLength), round(bb.YLength), round(bb.ZLength))
    return out


def roller_variants():
    """Per roller variant: filament (g) and the modelled flute / cell volume (cm3, the empty space inside Ø40 over
    the fluted length) against ovm_calc.volume_per_rev, to check the calculation against the solid."""
    import ovm_calc
    a, b = P.studded_span()
    envelope = G.cyl_x(P.roller_d, a, b)
    out = {}
    for k in P.ROLLERS:
        s = G.roller(k)
        plug = G.cyl_x(P.d_socket[0] + 1, P.roller_x[1] - P.d_socket[2] - 1, P.roller_x[1])   # fill the D socket
        model = envelope.Volume - s.fuse(plug).common(envelope).Volume
        calc = ovm_calc.volume_per_rev(k)
        out[k] = {"g": round(s.Volume * P.petg * P.infill_eff, 1), "cm3_model": round(model / 1000.0, 2),
                  "cm3_calc": round(calc / 1000.0, 2), "diff_pct": round(100.0 * (model - calc) / calc, 2),
                  "valid": s.isValid(), "solids": len(s.Solids)}
    return out


def mass_properties():
    """Filament per printed part (solid volume x density x infill_eff), total and cost; plus the stepper."""
    parts, total = {}, 0.0
    for n in printed():
        fn, _, _, dens, _ = PARTS[n]
        g = fn().Volume * dens * P.infill_eff
        parts[n] = round(g, 1)
        total += g
    return {"parts_g": parts, "printed_g": round(total), "stepper_g": round(P.stepper_kg * 1000),
            "rig_g": round(total + P.stepper_kg * 1000 - parts["tray"]),
            "filament_eur": round(total / 1000.0 * P.filament_eur_kg, 2)}


def export_stl(folder=STL_DIR, deflection=0.02, helical=(0.05, 0.2)):
    """STL per printed part in the print orientation. The swept helical flutes mesh to 11 - 14 MB at 0.02 mm /
    0.1 rad; 'helical' (linear mm, angular rad) gives about 3 MB at 0.1 % volume difference."""
    import MeshPart
    os.makedirs(folder, exist_ok=True)
    out = []
    for n in printed_all():
        lin, ang = deflection, 0.1
        if n.startswith("roller_") and P.ROLLERS[n.split("_", 1)[1]]["kind"] == "helical":
            lin, ang = helical
        mesh = MeshPart.meshFromShape(Shape=print_shape(n), LinearDeflection=lin, AngularDeflection=ang,
                                      Relative=False)
        path = os.path.join(folder, "ovm_%s.stl" % n)
        mesh.write(path)
        out.append(path)
    return out


